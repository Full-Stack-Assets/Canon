#!/usr/bin/env node
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createCanonIndex } from "../mcp/canon-index.mjs";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDirectory, "..");
const output = path.join(root, "mcp", "generated", "canon-snapshot.mjs");
const index = await createCanonIndex({ root });
const serialized = JSON.stringify(index.documents);
const digest = createHash("sha256").update(serialized).digest("hex");
const moduleSource = `// Generated by scripts/build-mcp-snapshot.mjs. Do not edit manually.\nexport const CANON_SNAPSHOT = Object.freeze({\n  sha256: ${JSON.stringify(digest)},\n  documentCount: ${index.documents.length},\n  documents: ${JSON.stringify(index.documents, null, 2)},\n});\n`;

await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, moduleSource, "utf8");
process.stdout.write(
  `Wrote ${path.relative(root, output)} (${index.documents.length} documents, sha256:${digest})\n`,
);
